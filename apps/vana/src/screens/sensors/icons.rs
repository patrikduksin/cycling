//! Source: https://app.paper.design/file/01M2KXNPZ2GGT5CXJ71Y979SE9/1-0

pub(super) fn pixel(device_type: u8, x: usize, y: usize) -> bool {
    if x >= 22 || y >= 20 {
        return false;
    }
    let index = match device_type {
        120 => 0,
        11 => 1,
        123 => 2,
        40 => 3,
        122 => 4,
        121 => 5,
        34 => 6,
        17 => 7,
        35 => 8,
        _ => 9,
    };
    GLYPHS[index][y] & (1 << x) != 0
}

